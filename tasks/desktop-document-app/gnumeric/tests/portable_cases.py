def typeset_rows(text,extension):
    """Read this fixture's authored rows without freezing renderer macros."""
    if extension=='tex':
        text='\n'.join(re.sub(r'(?<!\\)%.*','',line) for line in text.splitlines())
        text=re.sub(r'\\gnumericPB\{[^{}]*\}','',text)
        text=re.sub(r'\\(?:begin|end)\{[^{}]*\}','',text)
        text=re.sub(r'\\(?:gnumbox|textbf|textit|textrm|mbox)(?:\[[^\]]*\])?\{([^{}]*)\}',r'\1',text)
        rows=text.split('\\\\')
    else:
        text=text.replace('\\.','.').replace('\\-','-').replace('−','-')
        rows=text.splitlines()
    result={}
    for row in rows:
        for label in ('North','South','Sum','West'):
            match=re.search(r'\b'+label+r'\b',row)
            if match:
                numbers=re.findall(r'(?<![\w.])[+-]?\d+(?:\.\d+)?(?![\w.])',row[match.end():])
                assert numbers,'typeset row lost its numeric cell: '+label
                result[label]=float(numbers[-1])
    assert {'North','South','Sum'}<=set(result),'typeset output lost its report rows'
    return result


def legacy_inputs():
    sc=b'# This data file was generated by the Spreadsheet Calculator.\nleftstring A0 = "Legacy input"\nlet B1 = 17\nlet B2 = -4.25\nlet C1 = B1*3\nlet C2 = @sum(B1:B2)\n'
    oleo=b'# GNU Oleo spreadsheet\nC;r1;c1;K"Legacy input"\nC;r2;c2;K17\nC;r3;c2;K-4.25\nC;r2;c3;ER2C2*3\nC;r3;c3;ER2C2+R3C2\n'
    xml=b'''<?xml version="1.0"?><Workbook xmlns="urn:schemas-microsoft-com:office:spreadsheet" xmlns:ss="urn:schemas-microsoft-com:office:spreadsheet"><Worksheet ss:Name="Legacy"><Table><Row><Cell><Data ss:Type="String">Legacy input</Data></Cell></Row><Row><Cell ss:Index="2"><Data ss:Type="Number">17</Data></Cell><Cell ss:Formula="=RC[-1]*3"><Data ss:Type="Number">0</Data></Cell></Row><Row><Cell ss:Index="2"><Data ss:Type="Number">-4.25</Data></Cell><Cell ss:Formula="=SUM(R[-1]C[-1]:RC[-1])"><Data ss:Type="Number">0</Data></Cell></Row></Table></Worksheet></Workbook>'''
    fields=[('NAME','C',16,0),('AMOUNT','N',10,2),('ACTIVE','L',1,0),('DAY','D',8,0)]
    header=bytearray(32);header[:4]=bytes([3,124,1,1]);struct.pack_into('<IHH',header,4,2,33+32*len(fields),1+sum(f[2] for f in fields))
    body=bytearray(header)
    for name,kind,width,decimals in fields:
        descriptor=bytearray(32);descriptor[:len(name)]=name.encode();descriptor[11]=ord(kind);descriptor[16]=width;descriptor[17]=decimals;body+=descriptor
    body+=b'\r'
    for name,amount,active,day in [('First',17.5,'T','20240229'),('Second',-4.25,'F','20241231')]:
        body+=b' '+name.encode().ljust(16)+f'{amount:10.2f}'.encode()+active.encode()+day.encode()
    body+=b'\x1a'
    return [('sc','sc','Gnumeric_sc:sc',sc,['A1','B2','B3','C2','C3']),
            ('oleo','oleo','Gnumeric_oleo:oleo',oleo,['A1','B2','B3','C2','C3']),
            ('spreadsheetml','xml','Gnumeric_Excel:excel_xml',xml,['A1','B2','B3','C2','C3']),
            ('dbase','dbf','Gnumeric_xbase:xbase',bytes(body),['A1','A2','B2','C2','D2','A3','B3','C3','D3'])]


def build():
    result=[];wid='program-legacy-imports';cps=[]
    for name,ext,importer,raw,cells in legacy_inputs():
        cps.append({'id':name,'goal':'Import and recalculate an independently authored '+name+' document.',
          'assertions':[{'id':f'{wid}/{name}/{cell.lower()}','channel':'backend','method':'program',
                         'requirement':name+' import retains the typed value or recalculated formula at '+cell+'.',
                         'check':{'kind':'legacy','format':name,'cell':cell}} for cell in cells]})
    result.append({'id':wid,'feature':'legacy-imports','execution':'program','initial_state':'Fresh application and exchange folders.',
                   'setup':[],'inputs':{},'checkpoints':cps})
    wid='program-document-export';cps=[]
    for id,ext,exporter,options in [('pdf-a4','pdf','Gnumeric_pdf:pdf_assistant','paper=A4'),
                                  ('pdf-letter','pdf','Gnumeric_pdf:pdf_assistant','paper=Letter'),
                                  ('pdf-sheet','pdf','Gnumeric_pdf:pdf_assistant','sheet=Second'),
                                  ('html32','html','Gnumeric_html:html32',''),
                                  ('html-fragment','html','Gnumeric_html:html40frag',''),
                                  ('latex','tex','Gnumeric_html:latex',''),
                                  ('latex-table','tex','Gnumeric_html:latex_table',''),
                                  ('troff','troff','Gnumeric_html:roff','')]:
        aspects=['page-size'] if id=='pdf-letter' else ['content','page-size'] if id=='pdf-a4' else ['content']
        cps.append({'id':id,'goal':'Export a printable workbook with '+id+'.','depends_on':['setup:input'],
          'assertions':[{'id':f'{wid}/{id}/{aspect}','channel':'backend','method':'program',
                         'requirement':id+' retains the requested '+aspect+'.',
                         'check':{'kind':'document-export','ext':ext,'exporter':exporter,'options':options,'aspect':aspect}} for aspect in aspects]})
    result.append({'id':wid,'feature':'document-export','execution':'program','initial_state':'Fresh application and exchange folders.',
                   'setup':[{'id':'input','op':'portable-input'}],'inputs':{},'checkpoints':cps})
    return result


