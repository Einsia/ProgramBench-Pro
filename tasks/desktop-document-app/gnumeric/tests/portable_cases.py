def evaluate(ctx,cp,a):
    c=a['check'];key=('portable',cp['id'])
    if key not in ctx.state:
        try:
            if c['kind']=='legacy':
                name,ext,importer,raw,cells=next(x for x in legacy_inputs() if x[0]==c['format'])
                checks.upload(ctx,name+'.'+ext,raw)
                checks.convert(ctx,'inbox/'+name+'.'+ext,'outbox/'+name+'.xlsx',['--import-type',importer,'--recalc'])
                value=checks.workbook(checks.download(ctx,name+'.xlsx'),values_only=True)
            else:
                options=['--export-type',c['exporter'],'--recalc']
                if c['options']:options+=['--export-options',c['options']]
                filename=cp['id']+'.'+c['ext'];checks.convert(ctx,'inbox/print.gnumeric','outbox/'+filename,options)
                raw=checks.download(ctx,filename)
                assert raw,'exported document is empty'
                if c['ext']=='pdf':
                    import fitz
                    book=fitz.open(stream=raw,filetype='pdf')
                    value={'content':[' '.join(re.sub(r'^(?:Report|Second)\s+Page\s+\d+\s*','',p.get_text()).replace('−','-').split()) for p in book],
                           'page-size':[[round(p.rect.width,1),round(p.rect.height,1)] for p in book]}
                    assert value['content'] and all(value['content']),'PDF has no readable worksheet content'
                elif c['ext']=='html':
                    from lxml import html
                    root=html.fromstring(raw)
                    value={'content':[checks.table_token(' '.join(''.join(n.itertext()).split())) for n in root.xpath('//td | //th')]}
                    assert checks.table_token('North') in value['content'],'HTML table lost the worksheet content'
                else:
                    text=raw.decode('utf-8')
                    assert 'North' in text and 'South' in text,'typeset export lost worksheet content'
                    value={'content':typeset_rows(text,c['ext'])}
            ctx.state[key]=(value,None)
        except Exception as error:ctx.state[key]=(None,error)
    value,error=ctx.state[key]
    if error is not None:raise error
    if c['kind']=='legacy':
        observed=checks.cell_value(value,value.sheetnames[0],c['cell'])
        if ctx.record:assert observed['type'] not in ('blank','error'),'legacy input did not produce a typed result'
        return observed
    return {c['aspect']:value[c['aspect']]}
