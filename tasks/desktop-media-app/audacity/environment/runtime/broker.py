def catalog():
    commands = {c['id']: c for c in CATALOG['commands']}
    allowed = set(COMMANDS_ALLOWED)
    schemas = {name: {p['key']: p for p in spec.get('params', [])} for name, spec in commands.items()}
    preferences = {p['id']: p for p in CATALOG['preferences'] if isinstance(p, dict)
                   and p.get('id', '').startswith(PREFERENCE_PREFIXES)}
    preferences['/FileFormats/ExportFormat_SF1'] = {
        'id': '/FileFormats/ExportFormat_SF1', 'type': 'number', 'maximum': 0xffffff,
        'description': 'The PCM exporter header selector; per-header encodings are exposed with it.'}
    for header, code in PCM_HEADERS:
        name = f'/FileFormats/ExportFormat_SF1_Type/{header}_{code:x}'
        preferences[name] = {'id': name, 'type': 'number', 'maximum': 0xffff}

    for name in ('/Quality/DitherAlgorithmChoice', '/Quality/HQDitherAlgorithmChoice'):
        preferences[name] = {'id': name, 'type': 'enum', 'enum': ['None', 'Rectangle', 'Triangle', 'Shaped']}
    return allowed, schemas, preferences, [commands[name] for name in sorted(commands) if name in allowed]


