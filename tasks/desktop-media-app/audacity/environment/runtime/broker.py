class AudacityProduct(runtime.Product):
    """start.sh with the instance layout plus the owned document areas."""

    def prepare(self, fresh):
        super().prepare(fresh)
        exchange.prepare(self, AREAS)


class Broker:
    def __init__(self, config):
        self.config = config
        self.state = Path(config.state)
        self.log = runtime.BoundedLog(config.log_dir)
        directories = {**runtime.layout(config.state), 'PBP_AUDIO_PIPE_DIR': self.state/'pipes'}
        self.product = AudacityProduct(config, log=self.log, directories=directories)
        self.session = self.desk = None
        self.pipe = None
        self.pipe_failure = None
        self.stale = None
        self.launched = 0.
        self.replies = 0
        self.downloads, self.seen, self.serial = {}, {}, 0
        self.lock = threading.RLock()
        self.hide = runtime.redactor(config.solution, config.state, config.work, config.log_dir,
                                     Path(__file__).resolve().parent, '/app/solution', '/reference')

    # -- lifecycle ----------------------------------------------------------------------------------------------
    def area(self, name):
        return self.state/'files'/name

    def start_session(self):
        if self.session is not None:
            self.session.close()
        if self.desk is not None:
            self.desk.close()
        self.session = desktop.DesktopSession(user=self.config.user, screen=SCREEN, maximize=True, audio=True,
                                              log_dir=Path(self.config.log_dir)/'desktop').start()
        self.desk = desktop.Desktop(self.session, settle=SETTLE, log_dir=Path(self.config.log_dir)/'desktop',
                                    pointer_guard=self.guard_pointer)

    def drop_pipe(self):
        if self.pipe is not None:
            self.pipe.close()
            self.stale = self.pipe
        self.pipe = None
        self.pipe_failure = None

    def start(self, fresh):
        """Start (fresh: a new desktop session and empty instance) and wait for an accessible window."""
        self.product.stop()
        self.drop_pipe()
        if self.stale is not None:
            # The stock module leaves its FIFOs behind; never attach to a stopped process's endpoints.
            self.stale.unlink_stale()
            self.stale = None
        if fresh or self.session is None or not self.session.alive():
            self.start_session()
        if fresh:
            self.downloads.clear()
            self.seen.clear()
        self.product.extra = {key: value for key, value in self.session.env().items()
                              if key not in ('HOME', 'TMPDIR', 'XDG_CACHE_HOME', 'XDG_CONFIG_HOME', 'DATA_DIR')}
        started = self.product.start(fresh)
        self.launched, self.replies = time.monotonic(), 0
        if started:
            runtime.wait_until(self.product, lambda: self.desk.ready(minimum=(200, 150)),
                               failure=f'the application showed no accessible window within '
                                       f'{self.config.ready_timeout:g} s')
        return self.status()

    def status(self):
        value = self.product.status()
        value['scripting'] = {'connected': self.pipe is not None,
                              'detail': self.pipe_failure or ('connected' if self.pipe else 'not connected yet')}
        return value

    def close(self):
        self.product.stop()
        self.drop_pipe()
        if self.desk is not None:
            self.desk.close()
        if self.session is not None:
            self.session.close()

    # -- scripting ----------------------------------------------------------------------------------------------
    def connect(self):
        if self.pipe is not None:
            return
        if self.pipe_failure:
            raise ValueError(self.pipe_failure)
        if not self.product.running():
            raise ValueError('the application is not running; use restart or reset')
        client = PipeClient(self.state/'pipes', self.product.account().pw_uid)
        try:
            client.connect(max(self.launched+PIPE_SECONDS, time.monotonic()+.5))
        except PipeError as exc:
            raise ValueError(str(exc)) from None
        self.pipe = client

    def validate_script(self, name, params):
        if name not in ALLOWED:
            raise ValueError('product command is not exposed; see script_commands and menu_commands in help')
        if not isinstance(params, dict):
            raise ValueError('params must be a JSON object')
        schema = SCHEMAS.get(name, {})
        unknown = sorted(set(params)-set(schema))
        if unknown:
            raise ValueError('unknown command parameter: '+', '.join(unknown))
        for key, value in params.items():
            if not isinstance(value, (str, int, float, bool)) or isinstance(value, float) and not math.isfinite(value):
                raise ValueError(f'parameter {key} must be a finite scalar')
            if isinstance(value, str) and (len(value) > 1000 or any(ord(c) < 32 for c in value)):
                raise ValueError(f'invalid text in parameter {key}')
            if 'enum' in schema[key] and value not in schema[key]['enum']:
                raise ValueError(f'parameter {key} must be one of the catalog choices')
        params = dict(params)
        if name in ('GetPreference', 'SetPreference'):
            preference = params.get('Name')
            if preference not in PREFERENCES:
                raise ValueError('preference is not exposed; see preferences in help')
            if name == 'SetPreference':
                rule, value = PREFERENCES[preference], params.get('Value')
                if not isinstance(value, str) or '/' in value or '\\' in value:
                    raise ValueError('invalid preference value')
                if 'enum' in rule and value not in rule['enum']:
                    raise ValueError('invalid preference choice')
                if rule.get('type') == 'bool' and value not in ('0', '1', 'true', 'false', 'True', 'False'):
                    raise ValueError('invalid boolean preference')
                if rule.get('type') == 'number':
                    try:
                        number = float(value)
                    except ValueError:
                        raise ValueError('invalid numeric preference') from None
                    if not math.isfinite(number) or abs(number) > rule.get('maximum', 1_000_000):
                        raise ValueError('invalid numeric preference')
        if name in FILE_COMMANDS:
            given = str(params.get('Filename') or '')
            path = given if '/' in given else str(self.area(FILE_COMMANDS[name]) / basename(given))
            params['Filename'] = str(self.document_path(path, where='a file parameter'))
            if name == 'Export2' and Path(params['Filename']).suffix.casefold() not in EXPORT_SUFFIXES:
                raise ValueError('Export2 accepts the audio formats listed in export_suffixes')
        return params

    def titles(self):
        return [str(w.get('title', '')) for w in self.desk.windows()]

    def watch(self, notices):
        """Acknowledge the product's own import-error and orphan-file messages while a command runs."""
        titles = self.titles()
        if 'Error Importing' in titles:
            texts = []
            try:
                observed = self.desk.inspect()
                texts = [n.get('text') or n.get('name') for n in observed.get('nodes', []) if n.get('role') == 'label']
            except Exception:
                pass
            notices.append({'title': 'Error Importing', 'messages': [t for t in texts if t]})
            self.desk.act({'op': 'click', 'target': {'role': 'button', 'name': 'OK'}})
        elif any('Orphan Block File' in title for title in titles):
            notices.append({'title': 'Warning - Orphan Block File(s)'})
            self.desk.act({'op': 'click', 'target': {'role': 'radio button',
                                                     'name': 'Continue without deleting; ignore the extra files this session'}})
            self.desk.act({'op': 'click', 'target': {'role': 'button', 'name': 'OK'}})

    def script(self, data):
        self.unsafe()
        name = data['command']
        params = self.validate_script(name, data.get('params', {}))
        self.connect()
        timeout = FIRST_REPLY_SECONDS if self.replies == 0 else REPLY_SECONDS
        holder, done, notices = {}, threading.Event(), []

        def invoke():
            try:
                holder['response'] = self.pipe.command(name, params, timeout)
            except Exception as exc:
                holder['error'] = exc
            finally:
                done.set()
        threading.Thread(target=invoke, daemon=True).start()
        deadline = time.monotonic()+timeout+2
        while not done.wait(.25) and time.monotonic() < deadline:
            try:
                self.unsafe()
            except ValueError:
                self.drop_pipe()
                self.pipe_failure = 'the scripting connection was closed after an unavailable dialog; restart or reset'
                raise
            try:
                self.watch(notices)
            except desktop.DesktopError:
                pass
        if not done.is_set() or 'error' in holder:
            error = holder.get('error')
            detail = str(error) if error else f'product command {name} did not answer within {timeout:g} s'
            self.pipe.close()
            self.pipe = None
            self.pipe_failure = 'the scripting connection was closed after an unanswered request ('+detail+\
                                '); inspect the visible window, then use restart or reset'
            self.unsafe()
            raise ValueError(self.pipe_failure)
        self.unsafe()
        self.replies += 1
        response = holder['response']
        if isinstance(response.get('body'), str) and '\x00' in response['body']:
            raise ValueError('upstream scripting reply is invalid; observe this state through the desktop and exports')
        if notices:
            response['notifications'] = notices
        if name == 'Export2' and response['ok']:
            path = Path(params['Filename'])
            if path.is_file() and not path.is_symlink():
                response['downloads'] = [self.register(path)]
        return response

    # -- documents ----------------------------------------------------------------------------------------------
    def upload(self, data):
        filename = basename(data['filename'])
        if not filename.casefold().endswith(UPLOAD_SUFFIXES):
            raise ValueError('uploads are audio, MIDI or label text documents (suffixes '+' '.join(UPLOAD_SUFFIXES)+')')
        payload = base64.b64decode(data['base64'], validate=True)
        if len(payload) > MAX_FILE:
            raise ValueError(f'upload exceeds {MAX_FILE} bytes')
        if any(marker in payload.lower() for marker in PROJECT_MARKERS):
            raise ValueError('project documents cannot be uploaded; save projects with the application')
        target = self.area('inputs')/filename
        exchange.write_regular(target, payload, self.product.account())
        return {'uploaded': True, 'filename': filename, 'size': len(payload)}

    def register(self, path):
        stat = exchange.file_info(path, MAX_FILE)
        self.seen[str(path)] = (stat.st_mtime_ns, stat.st_size)
        self.serial += 1
        ref = f'd{self.serial}'
        self.downloads[ref] = path
        return {'ref': ref, 'filename': path.name, 'size': stat.st_size}

    def scan(self):
        """Register bounded regular documents found through directory descriptors."""
        for area in ('outputs', 'projects'):
            directory = self.area(area)
            for name, info in exchange.inventory(directory, DOWNLOAD_SUFFIXES, MAX_FILE, recursive=False):
                path = directory / name
                if self.seen.get(str(path)) == (info.st_mtime_ns, info.st_size):
                    continue
                if info.st_size == 0 and path.suffix.casefold() != '.txt':
                    continue
                if path.suffix.casefold() == '.txt':
                    try:
                        for line in exchange.read_regular(path, MAX_FILE).decode('utf-8-sig').splitlines():
                            if line:
                                fields = line.split('\t')
                                if len(fields) < 3 or not all(math.isfinite(float(x)) for x in fields[:2]):
                                    raise ValueError('not a label file')
                    except (OSError, UnicodeError, ValueError):
                        continue
                try:
                    self.register(path)
                except (OSError, ValueError):
                    continue

    def list_files(self):
        self.scan()
        pending = []
        for ref, path in self.downloads.items():
            try:
                info = exchange.file_info(path, MAX_FILE)
            except (OSError, ValueError):
                continue
            item = {'ref': ref, 'filename': path.name, 'size': info.st_size}
            pending.append(item)
        names = [name for name, _ in exchange.inventory(self.area('inputs'), UPLOAD_SUFFIXES, MAX_FILE)]
        return {'inputs': names, 'downloads': pending}

    def download(self, data):
        ref = data['ref']
        if ref not in self.downloads:
            raise ValueError('unknown download reference; use list_files')
        path = self.downloads.pop(ref)
        try:
            payload = exchange.read_regular(path, MAX_FILE)
        except (OSError, ValueError):
            raise ValueError('the file is no longer available or exceeds the download limit') from None
        return {'filename': path.name, 'size': len(payload),
                'body_base64': base64.b64encode(payload).decode()}

    # -- desktop ------------------------------------------------------------------------------------------------
    def inside(self, value):
        """Whether an absolute path lies in the document areas (dot segments removed first)."""
        path = os.path.normpath(str(value))
        root = str(self.state/'files')
        return path == root or path.startswith(root+os.sep)

    def document_path(self, value, *, where):
        """Normalize an absolute document path and validate every existing component."""
        text = str(value).strip()
        if (not text.startswith('/') or text.startswith('//') or '://' in text or '\\' in text
                or len(text) > 4000 or any(ord(c) < 32 for c in text)):
            raise ValueError(f'{where} accepts absolute document paths only')
        path = Path(os.path.normpath(text))
        root = Path(os.path.normpath(str(self.state / 'files')))
        if not path.is_relative_to(root):
            raise ValueError(f'{where} is confined to the document folder {root}')
        # Check the original path too: normalization must not hide a link before a parent step.
        original = Path(text)
        if any(part.is_symlink() for part in (original, *original.parents)):
            raise ValueError(f'{where} does not follow symbolic links')
        if original.resolve() != path or root.resolve() != root:
            raise ValueError(f'{where} does not resolve to the document folder')
        return path


    def chooser_state(self):
        """Whether a file chooser is open, and the bounds of its open file-type lists, from a private observation
        (the caller's refs stay valid). A combo box's list is its own top-level menu in AT-SPI."""
        nodes = self.desk.inspect().get('nodes', [])
        if not any(n.get('role') == 'file chooser' for n in nodes):
            return False, []
        by_id = {n.get('ref'): n for n in nodes}
        popups = {n.get('parent') for n in nodes if n.get('role') == 'menu item'
                  and CHOOSER_FORMATS.search(str(n.get('name', '')).casefold())}
        return True, [by_id[ref]['bounds'] for ref in popups if ref in by_id and by_id[ref].get('role') == 'menu']

    @staticmethod
    def format_item(record):
        return record.get('role') == 'menu item' and bool(CHOOSER_FORMATS.search(str(record.get('name', '')).casefold()))

    def chooser_control(self, target):
        """The node a target designates; it must be inside the open file chooser."""
        if target is None:
            raise ValueError('coordinate input is not available in a file chooser; target its controls')
        record = self.desk.resolve(target)
        if not any(role == 'file chooser' for role, _name in record.get('chain', [])):
            raise ValueError('the control is outside the active file chooser')
        return record

    def over(self, request, popups):
        """A wheel request whose point lies on an open file-type list."""
        if request.get('target') is not None:
            x, y, w, h = self.desk.resolve(request['target'])['bounds']
            point = (x+w//2, y+h//2)
        elif 'x' in request and 'y' in request:
            point = (request['x'], request['y'])
        else:
            return False
        return any(desktop.bounds_contain(box, *point) for box in popups)

    @staticmethod
    def filename_field(node):
        return node.get('role') in ('text', 'entry') and 'editable' in node.get('states', []) \
            and str(node.get('name', '')).rstrip(':').casefold() != 'search'

    def confirm(self):
        observed = self.desk.observe(tree=True)
        by_ref = {n['ref']: n for n in observed.get('nodes', [])}

        def inside(node):
            seen = set()
            while node is not None and node['ref'] not in seen:
                if node.get('role') == 'file chooser':
                    return True
                seen.add(node['ref'])
                node = by_ref.get(node.get('parent'))
            return False
        nodes = [n for n in observed.get('nodes', []) if inside(n)]
        entries = [n for n in nodes if self.filename_field(n)]
        buttons = [n for n in nodes if n.get('role') in ('button', 'push button')
                   and str(n.get('name', '')).casefold() in ('save', 'open', 'import', 'export')]
        if not entries:
            raise ValueError('the file chooser shows no file-name field')
        typed = str(entries[0].get('text') or entries[0].get('value') or '')
        path = self.document_path(typed, where='a file chooser') if typed.strip() else None
        if path is None:
            raise ValueError('type an absolute document path before confirming the file chooser '
                             f'(for example {self.area("outputs")}/name.wav; Control+L opens the location field '
                             'of an Open dialog)')
        if path.is_symlink():
            raise ValueError('the chooser destination is a symbolic link')
        # One accessibility request sets, verifies and confirms the checked path: wx/GTK can briefly unpublish a
        # chooser between separate requests.
        self.desk.set_text({'ref': entries[0]['ref']}, str(path),
                           confirm={'ref': buttons[0]['ref']} if buttons else None)
        if not buttons:
            self.desk.act({'op': 'press', 'key': 'Return'})
        return {'confirmed': str(path), 'note': 'refs were renewed; observe again'}

    def forbidden(self):
        return [title for title in self.titles()
                if any(label.casefold() in title.casefold() for label in UNSAFE_DIALOGS)]

    def close_titles(self, titles):
        """Close windows by title through the window manager: Escape leaves the product's frames open."""
        for title in titles:
            try:
                subprocess.run(['wmctrl', '-F', '-c', title], env={**os.environ, **self.session.env()},
                               capture_output=True, timeout=10)
            except (OSError, subprocess.SubprocessError):
                continue

    def unsafe(self):
        titles = self.forbidden()
        if not titles:
            return
        self.desk.act({'op': 'press', 'key': 'Escape'})
        deadline = time.monotonic()+5
        while self.forbidden() and time.monotonic() < deadline:
            self.close_titles(self.forbidden())
            time.sleep(.3)
        raise ValueError('code, plug-in, macro, raw-data, log, library-loading and folder-choosing dialogs are '
                         'outside reference exploration')

    def guard_pointer(self, event):
        """Validate the pointer part of every desktop input before it is sent."""
        request = event['pointer']
        op = request['op']
        chooser, popups = self.chooser_state()
        if not chooser:
            return
        if popups and op in ('click', 'activate') and request.get('target') is not None \
                and self.format_item(self.desk.resolve(request['target'])):
            return
        if popups and op == 'scroll' and self.over(request, popups):
            return
        if op not in ('click', 'activate'):
            raise ValueError('file chooser navigation is not available')
        node = self.chooser_control(request.get('target'))
        label = str(node.get('name', '')).rstrip('.…').casefold()
        if node.get('role') in ('button', 'push button'):
            # Confirmation goes through confirm(), which validates the path and
            # invokes the accessible action without a pointer operation.
            if label == 'cancel':
                return
        elif node.get('role') in ('combo box', 'menu item'):
            if CHOOSER_FORMATS.search(label):
                return
        elif self.filename_field(node):
            return
        raise ValueError('file chooser navigation is not available')

    def gui(self, op, data):
        request = {key: value for key, value in data.items() if key != 'op'}
        if op in ('type', 'fill'):
            # Typed text is passed through unchanged; a filesystem path in it must stay in the document areas,
            # wherever it is typed (a file chooser or one of the product's own path fields).
            value = str(request.get('value', ''))
            if '\\' in value:
                raise ValueError('typed text does not contain backslashes; document paths use /')
            if '/' in value:
                self.document_path(value, where='a typed document path')
        if op in GUI_GUARDED:
            self.unsafe()
            chooser, popups = self.chooser_state()
            if not chooser:
                pass
            elif popups and op == 'press' and chord(request.get('key', '')) in POPUP_KEYS \
                    and request.get('target') is None:
                pass
            elif popups and op in ('click', 'activate') and request.get('target') is not None \
                    and self.format_item(self.desk.resolve(request['target'])):
                pass
            elif popups and op == 'scroll' and self.over(request, popups):
                pass
            elif op in ('type', 'fill'):
                if op == 'fill' or request.get('target') is not None:
                    if not self.filename_field(self.chooser_control(request.get('target'))):
                        raise ValueError('text in a file chooser goes into its file-name field')
                if op == 'type' and '/' in str(request.get('value', '')):
                    # A save dialog pre-fills a name and selects only its stem, so a typed path would keep the old
                    # extension. A path names the whole document: replace the field's content.
                    self.desk.act({'op': 'press', 'key': 'Control+a', **({'target': request['target']}
                                                                         if request.get('target') is not None else {})})
            elif op == 'press':
                key = chord(request.get('key', ''))
                if key not in CHOOSER_KEYS or request.get('target') is not None:
                    raise ValueError('keys in a file chooser are limited to Control+A, Control+L, Escape and Return')
                if key in ('return', 'enter'):
                    return self.confirm()
            elif op in ('click', 'activate'):
                node = self.chooser_control(request.get('target'))
                label = str(node.get('name', '')).rstrip('.…').casefold()
                if node.get('role') in ('button', 'push button'):
                    if label not in CHOOSER_BUTTONS:
                        raise ValueError('file chooser navigation is not available')
                    if label != 'cancel':
                        return self.confirm()
                elif node.get('role') in ('combo box', 'menu item'):
                    if not CHOOSER_FORMATS.search(label):
                        raise ValueError('file chooser navigation is not available')
                elif not self.filename_field(node):
                    raise ValueError('file chooser navigation is not available')
            else:
                raise ValueError('file chooser navigation is not available')
        result = self.desk.act({'op': op, **request})
        if op in GUI_GUARDED:
            self.unsafe()
        return result

    # -- dispatch -----------------------------------------------------------------------------------------------
    def notes(self):
        areas = ', '.join(f'{area} {self.area(area)}' for area in AREAS)
        return [f'Document areas: {areas}. Uploads arrive in the input area, the product reads and writes them as '
                'ordinary files, and files it leaves in the output and project areas can be downloaded.'
                if note == 'DOCUMENT_AREAS' else note for note in NOTES]

    def help(self):
        limits = dict(LIMITS, ready_seconds=self.config.ready_timeout)
        return runtime.help_document(PRODUCT, 'desktop', OPERATIONS, limits=limits, notes=self.notes(),
                                     examples=examples(self.area('inputs')),
                                     scripting_endpoint=SCRIPTING, export_suffixes=list(EXPORT_SUFFIXES), script_commands=SCRIPT_COMMANDS,
                                     menu_commands=sorted(ALLOWED-set(SCHEMAS)),
                                     preferences=sorted(PREFERENCES.values(), key=lambda p: p['id']))

    def dispatch(self, data):
        op = runtime.validate(OPERATIONS, data)
        if op == 'help':
            return self.help()
        if op == 'status':
            return self.status()
        if op == 'reset':
            return self.start(True)
        if op == 'restart':
            return self.start(False)
        if op == 'script':
            return self.script(data)
        if op == 'upload':
            return self.upload(data)
        if op == 'list_files':
            return self.list_files()
        if op == 'download':
            return self.download(data)
        if op in ('observe', 'windows', 'screenshot'):
            self.unsafe()
        if op == 'observe':
            return self.desk.observe(**{k: v for k, v in data.items() if k != 'op'})
        if op == 'windows':
            return {'windows': self.desk.windows()}
        if op == 'screenshot':
            return self.desk.screenshot(**{k: v for k, v in data.items() if k != 'op'})
        return self.gui(op, data)

    def redact(self, text):
        """Text with private filesystem locations replaced; document paths stay readable (they are public)."""
        text = str(text)
        if '/' not in text:
            return text
        return re.sub(r'/[^\s\'"<>()\[\]{},;]*', lambda m: m.group(0) if self.inside(m.group(0))
                      else self.hide(m.group(0)), text)

    def clean(self, value):
        if isinstance(value, str):
            return self.redact(value)
        if isinstance(value, list):
            return [self.clean(item) for item in value]
        if isinstance(value, dict):
            return {key: (item if key in ('png_base64', 'body_base64') else self.clean(item))
                    for key, item in value.items()}
        return value


class Server(socketserver.ThreadingMixIn, http.server.HTTPServer):
    daemon_threads = True

    def __init__(self, sock, broker):
        super().__init__('blackbox', Handler, bind_and_activate=False)
        self.socket.close()
        self.socket, self.address_family = sock, sock.family
        self.server_name, self.server_port = 'localhost', 0
        self.broker = broker
        self.in_flight = 0
        self.count = threading.Lock()


class Handler(http.server.BaseHTTPRequestHandler):
    def log_message(self, *_):
        pass

    def address_string(self):
        return 'blackbox'

    def reply(self, code, value):
        data = json.dumps(value, ensure_ascii=False).encode()
        self.send_response(code)
        self.send_header('Content-Type', 'application/json')
        self.send_header('Content-Length', str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def do_POST(self):
        server, broker, started, op = self.server, self.server.broker, time.monotonic(), None
        with server.count:
            busy = server.in_flight >= MAX_IN_FLIGHT
            if not busy:
                server.in_flight += 1
        if busy:
            self.reply(429, {'error': 'Busy', 'detail': 'too many pending requests'})
            return
        try:
            if self.path != '/rpc':
                raise ValueError('unknown RPC endpoint')
            length = int(self.headers.get('Content-Length', '0'))
            if not 0 < length <= MAX_REQUEST:
                raise ValueError('request size outside limits')
            data = runtime.strict_json_loads(self.rfile.read(length))
            op = data.get('op', 'help') if isinstance(data, dict) else None
            outcome, done = {}, threading.Event()

            def work():
                try:
                    if not broker.lock.acquire(timeout=RPC_SECONDS):
                        raise TimeoutError
                    try:
                        outcome['value'] = broker.clean(broker.dispatch(data))
                    finally:
                        broker.lock.release()
                except BaseException as exc:
                    outcome['error'] = exc
                finally:
                    done.set()
            threading.Thread(target=work, daemon=True).start()
            if not done.wait(RPC_SECONDS):
                code, value = 408, {'error': 'TimeoutError', 'detail': 'black-box request deadline exceeded'}
            elif 'error' in outcome:
                exc = outcome['error']
                if isinstance(exc, TimeoutError) or getattr(exc, 'timeout', False) is True:
                    code, value = 408, {'error': 'TimeoutError', 'detail': 'black-box request deadline exceeded'}
                else:
                    code, value = 400, {'error': type(exc).__name__, 'detail': broker.redact(str(exc))[:600]}
            else:
                code, value = 200, outcome['value']
        except Exception as exc:
            code, value = 400, {'error': type(exc).__name__, 'detail': broker.redact(str(exc))[:600]}
        finally:
            with server.count:
                server.in_flight -= 1
        server.audit.record(op, code, time.monotonic()-started)
        self.reply(code, value)


def main(argv=None):
    config = runtime.options(state='/reference/state', log_dir='/reference', work='/reference/work',
                             ready_timeout=30.0).parse_args(argv)
    Path(config.work).mkdir(parents=True, exist_ok=True)
    # SIGTERM ends the process through the finally
    # block, which stops the product and closes the desktop session.
    runtime.exit_on_sigterm()
    broker = Broker(config)
    server = None
    try:
        # A product that fails to start is reported by status; the runtime keeps serving.
        broker.start(True)
        server = Server(runtime.listen(config.socket, config.socket_mode), broker)
        server.audit = runtime.Audit(Path(config.log_dir)/'rpc-audit.jsonl')
        server.serve_forever()
    finally:
        broker.close()
        if server is not None:
            server.server_close()


if __name__ == '__main__':
    main()
